import { index, integer, sqliteTable, text } from "drizzle-orm/sqlite-core";

export const jobs = sqliteTable(
  "jobs",
  {
    id: text("id").primaryKey(),
    title: text("title").notNull(),
    company: text("company").notNull(),
    location: text("location").notNull(),
    workMode: text("work_mode").notNull(),
    salary: text("salary").notNull(),
    postedAt: text("posted_at").notNull(),
    source: text("source").notNull(),
    sourceUrl: text("source_url"),
    canonicalUrl: text("canonical_url"),
    sourceHttpStatus: integer("source_http_status"),
    score: integer("score").notNull(),
    status: text("status").notNull(),
    skillsJson: text("skills_json").notNull(),
    gapsJson: text("gaps_json").notNull(),
    summary: text("summary").notNull(),
    rawDescription: text("raw_description").notNull(),
    recordType: text("record_type").notNull().default("imported"),
    verificationStatus: text("verification_status").notNull().default("unverified"),
    sourceKind: text("source_kind").notNull().default("webpage"),
    fetchedAt: text("fetched_at").notNull().default(""),
    verifiedAt: text("verified_at"),
    datePosted: text("date_posted"),
    validThrough: text("valid_through"),
    contentHash: text("content_hash").notNull().default(""),
    evidenceJson: text("evidence_json").notNull().default("[]"),
    jobType: text("job_type"),
    experienceLevel: text("experience_level"),
    roleFamily: text("role_family").notNull().default(""),
    sourceSite: text("source_site"),
    tailoredPath: text("tailored_path"),
    tailoredAt: text("tailored_at"),
    tailoredChanges: text("tailored_changes"),
    screenedOut: text("screened_out"),
    statusChangedAt: text("status_changed_at"),
    appliedAt: text("applied_at"),
    sponsorship: text("sponsorship").notNull().default("unknown"),
    sponsorshipNote: text("sponsorship_note"),
    tagsJson: text("tags_json").notNull().default("[]"),
    redFlagsJson: text("red_flags_json").notNull().default("[]"),
    createdAt: text("created_at").notNull(),
    updatedAt: text("updated_at").notNull(),
  },
  (table) => [
    index("jobs_created_at_idx").on(table.createdAt),
    index("jobs_status_idx").on(table.status),
    index("jobs_canonical_url_idx").on(table.canonicalUrl),
    index("jobs_content_hash_idx").on(table.contentHash),
    index("jobs_verification_idx").on(table.verificationStatus),
    index("jobs_role_family_idx").on(table.roleFamily),
  ],
);

export const applicationActions = sqliteTable("application_actions", {
  id: text("id").primaryKey(),
  jobId: text("job_id").notNull(),
  title: text("title").notNull(),
  kind: text("kind").notNull(),
  dueDate: text("due_date").notNull().default(""),
  url: text("url").notNull().default(""),
  notes: text("notes").notNull().default(""),
  completed: integer("completed").notNull().default(0),
  createdAt: text("created_at").notNull(),
  updatedAt: text("updated_at").notNull(),
});

